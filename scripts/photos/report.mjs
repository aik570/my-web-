#!/usr/bin/env node
// Lists every catalogue model with the picture the repair finder shows for it:
// exact photo (with licence), series picture ("Symbolbild") or none (drawing only).
// Writes project-audit/MODEL-PHOTOS.md.
//
//   node scripts/photos/report.mjs
import fs from 'node:fs';
import prices from '../../src/_data/prices.js';

const imgs = JSON.parse(fs.readFileSync('src/_data/modelImages.json', 'utf8'));
const data = await prices();
const rows = []; const count = { exact: 0, none: 0 };
for (const b of data.brands) {
  for (const m of b.models) {
    const exact = imgs.models[`${b.slug}/${m.slug}`];
    const kind = exact ? 'exact' : 'none';
    count[kind]++;
    rows.push(`| ${b.brand} | ${m.name} | ${m.category || ''} | ${exact ? `Produktfoto (${exact.license})` : '**fehlt** – Zeichnung'} |`);
  }
}
const total = rows.length;
const md = `# Model photos in the repair finder

Generated by \`node scripts/photos/report.mjs\` from \`src/_data/modelImages.json\`.

| | Models |
|---|---|
| Licensed product photo of exactly this model | ${count.exact} |
| Missing (the finder shows the drawing) | ${count.none} |
| **Total** | ${total} |

Only clean product photography is used (device isolated on a white, light or transparent background, whole device, no hands or surroundings), with a licence that allows commercial use on this website. New images: \`python3 scripts/photos/normalize.py <manifest.json>\` (crops, centres on a uniform white 600 × 800 canvas, registers licence and proof).

Licence situation checked on 31.10.2026: Samsung Mobile Press allows its material only "for your personal, informational and non-commercial use" – not usable on this website without written permission. iStock / Depositphotos: standard licence covers website use, but photos of branded phones there are usually marked "editorial use only", which excludes commercial use – only images without that mark may be bought. The reference shops' images are not reused (no licence).

| Brand | Model | Type | Picture |
|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync('project-audit/MODEL-PHOTOS.md', md);
// shopping list for the missing product photos (one row per model; fill file/licence/proof and import with normalize.py)
const csv = ['model_id;brand;model;type;expected_file'];
for (const b of data.brands) for (const m of b.models) if (!imgs.models[`${b.slug}/${m.slug}`]) csv.push([`${b.slug}/${m.slug}`, b.brand, m.name, m.category || '', `incoming/${b.slug}-${m.slug}.png`].join(';'));
fs.writeFileSync('project-audit/PRODUCT-PHOTOS-NEEDED.csv', csv.join('\n') + '\n');
console.log(count, 'of', total);
