#!/usr/bin/env node
// Lists every catalogue model with the picture the repair finder shows for it:
// exact photo (with licence), series picture ("Symbolbild") or none (drawing only).
// Writes project-audit/MODEL-PHOTOS.md.
//
//   node scripts/photos/report.mjs
import fs from 'node:fs';
import prices from '../../src/_data/prices.js';

const imgs = JSON.parse(fs.readFileSync('src/_data/modelImages.json', 'utf8'));
const data = await prices();
const rows = []; const count = { exact: 0, fallback: 0, none: 0 };
for (const b of data.brands) {
  for (const m of b.models) {
    const exact = imgs.models[`${b.slug}/${m.slug}`];
    const rule = !exact && imgs.rules.find((r) => r.brand === b.slug && new RegExp(r.pattern, 'i').test(m.name));
    const kind = exact ? 'exact' : rule ? 'fallback' : 'none';
    count[kind]++;
    rows.push(`| ${b.brand} | ${m.name} | ${m.category || ''} | ${exact ? `Foto (${exact.license}, ${exact.author})` : rule ? rule.label : '— (Zeichnung)'} |`);
  }
}
const total = rows.length;
const md = `# Model photos in the repair finder

Generated by \`node scripts/photos/report.mjs\` from \`src/_data/modelImages.json\`.

| | Models |
|---|---|
| Exact photo of the model | ${count.exact} |
| Series picture, labelled "Symbolbild … – nicht das exakte Modell" | ${count.fallback} |
| No picture (drawing only) | ${count.none} |
| **Total** | ${total} |

Exact photos come from Wikimedia Commons under free licences (CC0, CC BY, CC BY-SA). Author, licence and source are shown under the photo. The reference shops (houseofmobile-berlin.de, handy-reparatur-berlin030.de) were used only to check which device each model is; their images are not reused (no licence, "Alle Rechte vorbehalten").

| Brand | Model | Type | Picture |
|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync('project-audit/MODEL-PHOTOS.md', md);
console.log(count, 'of', total);
